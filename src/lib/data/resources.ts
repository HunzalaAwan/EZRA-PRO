export function getResourcesByTenant(tenantId: string): Resource[] {
  return RESOURCES.filter((resource) => resource.tenantId === tenantId)
}

export function getResourceById(id: string): Resource | undefined {
  return RESOURCES.find((resource) => resource.id === id)
}

/** Resources actually usable today — excludes maintenance and retired units. */
export function getAvailableResources(tenantId: string): Resource[] {
  return RESOURCES.filter((r) => r.tenantId === tenantId && r.status === 'available')
}
